/**
 * 🛡️ CYBER ACCESS MANAGER - VERSION 2026.5
 * ⚙️ MODULE 05: AUTOMATED PORT SWEEPER & PACKET ANALYZER
 * 👨‍💻 Developed by: Coding with Bandar
 * * المفهوم: الحلقات التكرارية (Loops) وأتمتة خطوط الدفاع في الذاكرة العشوائية RAM.
 */

public class portSweeper {
    public static void main(String[] args) {

        // ========================================================================
        // 🛡️ LOADER: STARTING CYBER ACCESS AUTO-SECURITY SYSTEMS
        // ========================================================================
        System.out.println("=========================================================");
        System.out.println("   ⚙️ CYBER ACCESS MANAGER v2026.5 - AUTOMATION ENGINE  ");
        System.out.println("=========================================================");
        System.out.println("⚠️ تنبيه: تم تفعيل الحراس التكراريين بداخل الذاكرة RAM...\n");


        // ------------------------------------------------------------------------
        // 🔥 PART 1: THE FOR LOOP (ملك الأتمتة المحددة - Scheduled Port Sweeper)
        // ------------------------------------------------------------------------
        System.out.println("[+] المرحلة الأولى: بدء مسح المنافذ الشبكية المجدولة...");
        System.out.println("---------------------------------------------------------");

        for (int port = 1; port <= 80; port++) {
            System.out.println("🔍 [فحص] -> جاري فحص المنفذ الأمني رقم: #" + port);
        }

        System.out.println("🟢 [نجاح] -> تم الانتهاء من مسح الـ 80 منفذ بنجاح. الوضع آمن.\n");


        // ------------------------------------------------------------------------
        // 🕵️‍♂️ PART 2: THE WHILE LOOP (الحارس المستمر - Continuous Packet Scanner)
        // ------------------------------------------------------------------------
        System.out.println("[+] المرحلة الثانية: تشغيل حارس الحزم المستمر في الخلفية...");
        System.out.println("---------------------------------------------------------");

        boolean isSystemSafe = true;
        int scannedPackets = 0;

        while (isSystemSafe) {
            scannedPackets++;
            System.out.println("📦 [تحليل] -> فحص الحزمة رقم: " + scannedPackets + " | الحالة: آمن");

            // جدار الفحص الذكي لكسر الحلقة اللانهائية فور رصد الخطر
            if (scannedPackets == 50) {
                System.out.println("\n🚨 [إنذار خطير] -> رصد حزمة خبيثة (Malicious Packet) في المنفذ!");
                System.out.println("🛑 [حظر] -> تم إيقاف محرك الفحص فوراً وتجميد العمليات.");
                isSystemSafe = false; // كسر الشرط بنجاح بداخل الـ RAM
            }
        }
        System.out.println("🟢 [حماية] -> الحارس المستمر أتم مهمته وأغلق البوابة تلقائياً.\n");


        // ------------------------------------------------------------------------
        // ⚡ PART 3: THE DO-WHILE LOOP (التنفيذ الإجباري - Decryption Attempt)
        // ------------------------------------------------------------------------
        System.out.println("[+] المرحلة الثالثة: بدء نظام فك تشفير الملفات الحساسة...");
        System.out.println("---------------------------------------------------------");

        int attempts = 0;
        do {
            System.out.println("🔐 [تشفير] -> محاولة فك تشفير الملفات... (المرة الأولى مجانية ورغم خطأ الشرط!)");
            attempts++;

            // كواليس الـ RAM: الكود هنا سيتنفذ مرة واحدة على الأقل بالملي
            // لأن الفحص يحدث عند نهاية القوس وليس في بدايته!
        } while (attempts < 0);

        System.out.println("---------------------------------------------------------");
        System.out.println("🛡️ [نهاية الفحص] -> جميع المحركات أدت وظيفتها.. النظام محمي 100%.");
        System.out.println("=========================================================");
    }
}